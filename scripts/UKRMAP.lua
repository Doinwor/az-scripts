script_name('UKRMAP')
script_author('FOREZIT')

local state = false
local radius = 5000
local color = 0x00FF00FF
local pool = {}

function main()
	while not isSampAvailable() do wait(100) end
	sampAddChatMessage(' >>{FFFFFF} Camshot v rot ot FOREZIT | {FF7070}Команда: /map', 0xFF7070)
	sampRegisterChatCommand('map', function() 
		state = not state
		printStyledString(state and '~g~ON' or '~r~OFF', 1000, 6)
		if not state then remove_all() end
	end)
	addEventHandler('onScriptTerminate', function(script, quit)
		if script == thisScript() then
			remove_all()
		end
	end)
	while true do
		if state then
			local A = { getCharCoordinates(PLAYER_PED) }
			for i, B in ipairs(coords) do
				local dist = getDistanceBetweenCoords3d(A[1], A[2], A[3], B[1], B[2], B[3])
				if dist <= radius and pool[i] == nil then
					pool[i] = addBlipForCoord(B[1], B[2], B[3])
					changeBlipColour(pool[i], color)
				elseif dist > radius and pool[i] ~= nil then
					removeBlip(pool[i])
					pool[i] = nil
				end
			end
		end
		wait(0)
	end
end

function remove_all()
	for i = 1, #coords do
		if pool[i] ~= nil then
			removeBlip(pool[i])
			pool[i] = nil
		end
	end
end

